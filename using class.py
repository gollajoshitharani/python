#class car
class Car:
    def __init__(int, make, model, year, color):
        int.make = make      # instance attribute
        int.model = model
        int.year = year
        int.color = color
        int.speed = 0        # default value
# Creating instances (objects) of Car
car1 = Car("Toyota", "Camry", 2022, "Red")
car2 = Car("Ford", "Mustang", 2023, "Black")
print(car1.make)   # Output: Toyota
print(car2.speed)  # Output: 0



